import AppKit
import Carbon.HIToolbox
import NachoComboCore

/// Clipboard history. macOS has no "clipboard changed" notification, so the general pasteboard's change count is read
/// twice a second (reading it needs no permission). Copies stay in memory; only pins are written, to the app's own
/// folder. The list opens at the pointer; pasting puts the item back on the clipboard and, with Accessibility, presses
/// ⌘V in the app that was in front. Copies that password managers mark as secret are skipped.
final class ClipboardModule: NSObject, FeatureModule {
    let id = ModuleID.clipboard
    var optionsProvider: () -> GadgetOptions = { .defaults }
    var onChange: (() -> Void)?
    /// Hands an item to File Shelf; false when the shelf is off.
    var sendToShelf: ((ClipboardItem) -> Bool)?

    private(set) var history = ClipboardHistory()
    private(set) var running = false
    private(set) var pasteCount = 0
    private(set) var lastResult = "-"
    private var timer: Timer?
    private var lastChange = 0
    private var panel: ClipboardPanel?

    /// Types other apps add to say "do not record this" (password managers, one-time codes).
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    static var pinsURL: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NachoCombo", isDirectory: true).appendingPathComponent("clipboard-pins.json")
    }

    var isPanelVisible: Bool { panel?.isVisible ?? false }

    func start() -> ModuleState {
        guard !running else { return .running }
        running = true
        history = ClipboardHistory(limit: optionsProvider().clipboardLimit, pins: ClipboardModule.loadPins())
        lastChange = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        return .running
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        panel?.close()
        panel = nil
        history = ClipboardHistory()
        running = false
    }

    func applyOptions() {
        guard running else { return }
        history.limit = optionsProvider().clipboardLimit
        panel?.reload()
    }

    // MARK: recording

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map { $0.rawValue })
        guard types.isDisjoint(with: ClipboardModule.secretTypes) else { lastResult = "skipped:secret"; return }
        guard var item = ClipboardModule.read(pasteboard, images: optionsProvider().clipboardImages) else { return }
        item.sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName
        if history.add(item) {
            if item.pinned { savePins() }
            panel?.reload()
            onChange?()
        }
    }

    static func read(_ pasteboard: NSPasteboard, images: Bool) -> ClipboardItem? {
        let fileOptions: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: fileOptions) as? [URL], !urls.isEmpty {
            return ClipboardItem(kind: .files, text: urls.map { $0.path }.joined(separator: "\n"))
        }
        if let string = pasteboard.string(forType: .string), !string.isEmpty {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.contains(where: { $0.isWhitespace }), let url = URL(string: trimmed),
               ["http", "https"].contains(url.scheme?.lowercased() ?? "") {
                return ClipboardItem(kind: .link, text: trimmed)
            }
            return ClipboardItem(kind: .text, text: string, rtf: pasteboard.data(forType: .rtf))
        }
        if images, let png = ShelfModule.pngData(from: pasteboard) {
            return ClipboardItem(kind: .image, text: "", imagePNG: png)
        }
        return nil
    }

    // MARK: the list

    func showPanel() {
        guard running else { return }
        if let panel = panel, panel.isVisible { panel.close(); return }
        let panel = ClipboardPanel(module: self)
        self.panel = panel
        panel.show(near: NSEvent.mouseLocation)
        onChange?()
    }

    func panelClosed() {
        panel = nil
        onChange?()
    }

    var accessibilityAllowed: Bool { AXIsProcessTrusted() }

    /// Puts the item on the clipboard and pastes it where the user was (the list never takes the app to the front, so
    /// that app is still the active one).
    func paste(_ item: ClipboardItem, plain: Bool) {
        write(item, plain: plain)
        panel?.close()
        pasteCount += 1
        guard optionsProvider().clipboardPasteDirectly, accessibilityAllowed else {
            lastResult = "copied"
            Toast.show("Copied. Press ⌘V to paste.", near: NSEvent.mouseLocation)
            return
        }
        lastResult = plain ? "pasted:plain" : "pasted"
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { ClipboardModule.pressCommandV() }
    }

    /// The last copy, without its formatting, into the app in front.
    func pastePlainLast() {
        guard running else { return }
        if let item = history.items.first(where: { $0.kind == .text || $0.kind == .link }) ?? history.items.first {
            paste(item, plain: true)
        }
    }

    func copy(_ item: ClipboardItem) {
        write(item, plain: false)
        Toast.show("Copied", near: NSEvent.mouseLocation)
    }

    private func write(_ item: ClipboardItem, plain: Bool) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            if !plain, let rtf = item.rtf { pasteboard.setData(rtf, forType: .rtf) }
            pasteboard.setString(item.text, forType: .string)
        case .link:
            pasteboard.setString(item.text, forType: .string)
        case .image:
            if let png = item.imagePNG {
                pasteboard.setData(png, forType: .png)
                if let tiff = NSImage(data: png)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
            }
        case .files:
            let urls = item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            pasteboard.writeObjects(urls)
        }
        // Our own write moves the item to the top instead of adding a second entry.
        lastChange = pasteboard.changeCount
        var moved = item
        moved.date = Date()
        history.add(moved)
        onChange?()
    }

    static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    func togglePin(_ id: UUID) {
        history.togglePin(id)
        savePins()
        panel?.reload()
        onChange?()
    }

    func remove(_ id: UUID) {
        let wasPinned = history.item(id)?.pinned ?? false
        history.remove(id)
        if wasPinned { savePins() }
        panel?.reload()
        onChange?()
    }

    func clearHistory() {
        history.clearUnpinned()
        panel?.reload()
        onChange?()
    }

    func shelve(_ item: ClipboardItem) {
        if sendToShelf?(item) == true {
            panel?.close()
        } else {
            Toast.show("Turn on File Shelf to send items there", near: NSEvent.mouseLocation)
        }
    }

    // MARK: pins

    static func loadPins() -> [ClipboardItem] {
        guard let data = try? Data(contentsOf: pinsURL) else { return [] }
        return (try? JSONDecoder().decode([ClipboardItem].self, from: data)) ?? []
    }

    private func savePins() {
        let pins = history.pins
        do {
            try FileManager.default.createDirectory(at: ClipboardModule.pinsURL.deletingLastPathComponent(),
                                                    withIntermediateDirectories: true)
            if pins.isEmpty {
                try? FileManager.default.removeItem(at: ClipboardModule.pinsURL)
            } else {
                try JSONEncoder().encode(pins).write(to: ClipboardModule.pinsURL, options: .atomic)
            }
        } catch {
            lastResult = "error:pins"
        }
    }

    // Debug channel helpers.
    func debugAdd(_ text: String) {
        history.add(ClipboardItem(kind: .text, text: text, sourceApp: "Debug"))
        panel?.reload()
        onChange?()
    }

    var diagnostics: [String: String] {
        [
            "running": "\(running)",
            "timerActive": "\(timer != nil)",
            "items": "\(history.items.count)",
            "pins": "\(history.pins.count)",
            "panelVisible": "\(isPanelVisible)",
            "pasteCount": "\(pasteCount)",
            "accessibility": "\(accessibilityAllowed)",
            "lastResult": lastResult,
            "first": history.items.first.map { "\($0.kind.rawValue):\($0.title.prefix(40))" } ?? "-",
        ]
    }
}

// MARK: - The list at the pointer

/// A non-activating panel: it takes the keyboard for the search field while the app the user works in stays active,
/// so the paste lands there.
final class ClipboardPanel: NSPanel, NSTableViewDataSource, NSTableViewDelegate, NSSearchFieldDelegate, NSWindowDelegate {
    private weak var module: ClipboardModule?
    private let search = NSSearchField()
    private let table = NSTableView()
    private let empty = UI.label("Nothing copied yet", style: .callout, color: UI.secondaryText)
    private var shown: [ClipboardItem] = []
    private var keyMonitor: Any?
    static let size = NSSize(width: 380, height: 440)

    init(module: ClipboardModule) {
        self.module = module
        super.init(contentRect: NSRect(origin: .zero, size: ClipboardPanel.size),
                   styleMask: [.nonactivatingPanel, .titled, .fullSizeContentView], backing: .buffered, defer: false)
        titleVisibility = .hidden
        titlebarAppearsTransparent = true
        standardWindowButton(.closeButton)?.isHidden = true
        standardWindowButton(.miniaturizeButton)?.isHidden = true
        standardWindowButton(.zoomButton)?.isHidden = true
        isFloatingPanel = true
        level = .popUpMenu
        hidesOnDeactivate = false
        isReleasedWhenClosed = false
        becomesKeyOnlyIfNeeded = false
        collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        isMovableByWindowBackground = true
        delegate = self
        setAccessibilityLabel("Clipboard History")
        build()
        reload()
    }

    override var canBecomeKey: Bool { true }

    private func build() {
        let effect = NSVisualEffectView()
        effect.material = .popover
        effect.state = .active
        effect.blendingMode = .behindWindow
        contentView = effect

        search.placeholderString = "Search what you copied"
        search.delegate = self
        search.font = UI.controlFont(.body)
        search.focusRingType = .none
        search.setAccessibilityIdentifier("clipboard-search")

        let column = NSTableColumn(identifier: NSUserInterfaceItemIdentifier("item"))
        column.width = ClipboardPanel.size.width - 24
        table.addTableColumn(column)
        table.headerView = nil
        table.rowHeight = 40
        table.intercellSpacing = NSSize(width: 0, height: 2)
        table.backgroundColor = .clear
        table.style = .plain
        table.selectionHighlightStyle = .regular
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(rowClicked)
        table.setAccessibilityIdentifier("clipboard-list")
        let scroll = NSScrollView()
        scroll.documentView = table
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.translatesAutoresizingMaskIntoConstraints = false

        let hint = UI.label("↩ Paste   ⌥↩ Plain text   ⌘P Pin   ⌘S To Shelf   ⌫ Remove", style: .caption1,
                            color: UI.tertiaryText)
        for view in [search, scroll, hint, empty] as [NSView] {
            view.translatesAutoresizingMaskIntoConstraints = false
            effect.addSubview(view)
        }
        NSLayoutConstraint.activate([
            search.topAnchor.constraint(equalTo: effect.topAnchor, constant: 30),
            search.leadingAnchor.constraint(equalTo: effect.leadingAnchor, constant: 12),
            search.trailingAnchor.constraint(equalTo: effect.trailingAnchor, constant: -12),
            scroll.topAnchor.constraint(equalTo: search.bottomAnchor, constant: 8),
            scroll.leadingAnchor.constraint(equalTo: effect.leadingAnchor, constant: 6),
            scroll.trailingAnchor.constraint(equalTo: effect.trailingAnchor, constant: -6),
            scroll.bottomAnchor.constraint(equalTo: hint.topAnchor, constant: -6),
            hint.leadingAnchor.constraint(equalTo: effect.leadingAnchor, constant: 14),
            hint.bottomAnchor.constraint(equalTo: effect.bottomAnchor, constant: -10),
            empty.centerXAnchor.constraint(equalTo: scroll.centerXAnchor),
            empty.centerYAnchor.constraint(equalTo: scroll.centerYAnchor),
        ])
    }

    func show(near point: NSPoint) {
        let screen = NSScreen.screens.first { NSMouseInRect(point, $0.frame, false) } ?? NSScreen.main
        let visible = screen?.visibleFrame ?? NSRect(x: 0, y: 0, width: 1440, height: 900)
        let size = ClipboardPanel.size
        let origin = NSPoint(x: min(max(point.x - 30, visible.minX + 8), visible.maxX - size.width - 8),
                             y: min(max(point.y - size.height + 20, visible.minY + 8), visible.maxY - size.height - 8))
        setFrame(NSRect(origin: origin, size: size), display: true)
        orderFrontRegardless()
        makeKey()
        makeFirstResponder(search)
        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            guard let self = self, event.window === self else { return event }
            return self.handleKey(event) ? nil : event
        }
    }

    override func close() {
        if let monitor = keyMonitor { NSEvent.removeMonitor(monitor) }
        keyMonitor = nil
        super.close()
        module?.panelClosed()
    }

    func windowDidResignKey(_ notification: Notification) { close() }

    func reload() {
        guard let module = module else { return }
        let selectedID = selected?.id
        shown = module.history.search(search.stringValue)
        table.reloadData()
        empty.isHidden = !shown.isEmpty
        empty.stringValue = search.stringValue.isEmpty ? "Nothing copied yet" : "No match"
        let row = selectedID.flatMap { id in shown.firstIndex { $0.id == id } } ?? 0
        if !shown.isEmpty { table.selectRowIndexes(IndexSet(integer: min(row, shown.count - 1)), byExtendingSelection: false) }
    }

    private var selected: ClipboardItem? {
        let row = table.selectedRow
        return shown.indices.contains(row) ? shown[row] : nil
    }

    // MARK: keys

    /// Return pastes, ⌥Return pastes plain text, ⌘1…9 paste one of the first nine, ⌘P pins, ⌘S sends to the shelf,
    /// ⌫ (with an empty search) removes, ↑ / ↓ move, Esc closes.
    private func handleKey(_ event: NSEvent) -> Bool {
        let flags = event.modifierFlags.intersection(.deviceIndependentFlagsMask)
        let command = flags.contains(.command)
        switch Int(event.keyCode) {
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if let item = selected { module?.paste(item, plain: flags.contains(.option)) }
            return true
        case kVK_Escape:
            close()
            return true
        case kVK_DownArrow, kVK_UpArrow:
            guard !shown.isEmpty else { return true }
            let step = event.keyCode == UInt16(kVK_DownArrow) ? 1 : -1
            let row = min(max(0, table.selectedRow + step), shown.count - 1)
            table.selectRowIndexes(IndexSet(integer: row), byExtendingSelection: false)
            table.scrollRowToVisible(row)
            return true
        case kVK_Delete, kVK_ForwardDelete:
            guard search.stringValue.isEmpty || command, let item = selected else { return false }
            module?.remove(item.id)
            return true
        default:
            break
        }
        guard command, let characters = event.charactersIgnoringModifiers?.lowercased() else { return false }
        if let digit = Int(characters), (1...9).contains(digit) {
            if shown.indices.contains(digit - 1) { module?.paste(shown[digit - 1], plain: flags.contains(.option)) }
            return true
        }
        switch characters {
        case "p": if let item = selected { module?.togglePin(item.id) }; return true
        case "s": if let item = selected { module?.shelve(item) }; return true
        case "c": if let item = selected { module?.copy(item); close() }; return true
        default: return false
        }
    }

    func controlTextDidChange(_ obj: Notification) { reload() }

    @objc private func rowClicked() {
        guard table.clickedRow >= 0, shown.indices.contains(table.clickedRow) else { return }
        module?.paste(shown[table.clickedRow], plain: NSEvent.modifierFlags.contains(.option))
    }

    // MARK: table

    func numberOfRows(in tableView: NSTableView) -> Int { shown.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let item = shown[row]
        let cell = NSTableCellView()
        let icon = NSImageView()
        icon.translatesAutoresizingMaskIntoConstraints = false
        icon.imageScaling = .scaleProportionallyUpOrDown
        switch item.kind {
        case .image: icon.image = item.imagePNG.flatMap { NSImage(data: $0) }
        case .files:
            icon.image = NSWorkspace.shared.icon(forFile: String(item.text.split(separator: "\n").first ?? ""))
        case .link: icon.image = UI.symbol("link", size: 15, weight: .medium); icon.contentTintColor = .controlAccentColor
        case .text: icon.image = UI.symbol("text.alignleft", size: 15, weight: .medium); icon.contentTintColor = UI.secondaryText
        }
        let title = UI.label(item.kind == .image ? "Image" : item.title, style: .callout)
        title.lineBreakMode = .byTruncatingTail
        title.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        var meta: [String] = []
        if item.pinned { meta.append("Pinned") }
        if let app = item.sourceApp { meta.append(app) }
        meta.append(ClipboardPanel.age(item.date))
        let detail = UI.label(meta.joined(separator: " · "), style: .caption1, color: UI.secondaryText)
        let number = UI.label(row < 9 ? "⌘\(row + 1)" : "", style: .caption1, color: UI.tertiaryText)
        number.setContentCompressionResistancePriority(.required, for: .horizontal)
        let pin = NSImageView(image: UI.symbol("pin.fill", size: 10, weight: .semibold) ?? NSImage())
        pin.contentTintColor = Brand.nachoDeep
        pin.isHidden = !item.pinned
        let text = UI.vstack([title, detail], spacing: 1)
        let line = UI.hstack([icon, text, UI.spacer(), pin, number], spacing: 8)
        cell.addSubview(line)
        NSLayoutConstraint.activate([
            icon.widthAnchor.constraint(equalToConstant: 26),
            icon.heightAnchor.constraint(equalToConstant: 26),
            line.leadingAnchor.constraint(equalTo: cell.leadingAnchor, constant: 6),
            line.trailingAnchor.constraint(equalTo: cell.trailingAnchor, constant: -8),
            line.centerYAnchor.constraint(equalTo: cell.centerYAnchor),
        ])
        cell.setAccessibilityLabel("\(item.kind.displayName): \(item.title)" + (item.pinned ? ", pinned" : ""))
        return cell
    }

    static func age(_ date: Date) -> String {
        let seconds = Int(Date().timeIntervalSince(date))
        if seconds < 60 { return "just now" }
        if seconds < 3600 { return "\(seconds / 60) min ago" }
        if seconds < 86_400 { return "\(seconds / 3600) h ago" }
        return "\(seconds / 86_400) d ago"
    }
}
