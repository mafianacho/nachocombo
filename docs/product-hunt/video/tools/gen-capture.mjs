#!/usr/bin/env node
// Generates, from capture-manifest.json: capture.sh (the shoot script for a Mac) and the capture table inside STORYBOARD.md
// (between the capture-table markers). So the table the next step reads and the script it runs can never differ.
//   node tools/gen-capture.mjs --write   regenerate both files
//   node tools/gen-capture.mjs --check   exit 1 when either file is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'capture-manifest.json'), 'utf8'));
const mode = process.argv.includes('--write') ? 'write' : 'check';
const shot = manifest.captures.filter((c) => !c.file.startsWith('repo:'));
const quote = (s) => s.replace(/\{out\}/g, '"$OUT/@FILE@"');

function script() {
  const out = [
    '#!/usr/bin/env bash',
    '# GENERATED by tools/gen-capture.mjs from capture-manifest.json. Do not edit; change the manifest and regenerate.',
    '#',
    '# Shoots every capture PNG of the intro video from the app\'s own debug control channel (the same method as scripts/screenshots.sh).',
    '# Run it on a Mac that has a v0.13.0 (or newer) build, preferably a clean test user account. It refuses to start while another',
    '# Nacho Combo is running (the Mac may be shared): it never kills a process it did not start unless you set KILL_RUNNING=1.',
    '# It leaves the debug instance closed afterwards. Nothing is recorded from the screen; the app renders its own views.',
    '#   APP=/path/to/NachoCombo.app scripts-dir/capture.sh <out dir>',
    '# NOT YET RUN against a real build: ctl syntax comes from README.md and the source, see capture-manifest.json.',
    'set -euo pipefail',
    'APP="${APP:-build/NachoCombo.app}"',
    'BIN="$APP/Contents/MacOS/NachoCombo"',
    'OUT="${1:?usage: capture.sh <out dir>}"',
    'mkdir -p "$OUT"; OUT="$(cd "$OUT" && pwd)"',
    'if pgrep -x NachoCombo >/dev/null; then',
    '  if [ "${KILL_RUNNING:-0}" = 1 ]; then pkill -x NachoCombo || true; sleep 1',
    '  else echo "capture.sh: a NachoCombo process is already running; not touching it. Find out who uses it, or rerun with KILL_RUNNING=1 once it is yours to quit." >&2; exit 3; fi',
    'fi',
    '"$BIN" --debug-ctl >/dev/null 2>&1 &',
    'sleep 4',
    'ctl() { "$BIN" ctl "$@" >/dev/null; }',
    'trap \'ctl quit || true\' EXIT',
    '',
    '# setup (every capture below runs on sample data)',
    ...manifest.setup.map((c) => `ctl ${c}`),
    '',
  ];
  for (const c of shot) {
    out.push(`# ${c.file}: ${c.what}`);
    for (const cmd of c.commands) out.push(cmd.startsWith('sleep ') ? cmd : `ctl ${quote(cmd).replace('@FILE@', c.file)}`);
    out.push('');
  }
  out.push('# teardown', ...manifest.teardown.map((c) => `ctl ${c}`), '');
  out.push('missing=0');
  out.push(`for f in ${shot.map((c) => c.file).join(' ')}; do`);
  out.push('  [ -s "$OUT/$f" ] || { echo "missing or empty: $f" >&2; missing=1; }');
  out.push('done');
  out.push(`[ "$missing" = 0 ] && echo "all ${shot.length} captures written to $OUT" || exit 1`);
  return out.join('\n') + '\n';
}

function table() {
  const rows = ['| # | File | Scene | Subject | Exact `ctl` commands (in order, after the setup below) | Look | Min width |', '|---|---|---|---|---|---|---|'];
  manifest.captures.forEach((c, i) => {
    const cmds = c.commands.length ? c.commands.map((x) => (x.startsWith('sleep') ? `\`${x}\`` : `\`ctl ${x.replace('{out}', c.file)}\``)).join('<br>') : 'none: read from the repository at render time';
    rows.push(`| ${i + 1} | \`${c.file.replace('repo:', '')}\` | ${c.scene} | ${c.what} | ${cmds} | ${c.appearance} | ${c.minWidth} px |`);
  });
  return rows.join('\n');
}

const start = '<!-- capture-table:start (generated by tools/gen-capture.mjs) -->';
const end = '<!-- capture-table:end -->';
const sbPath = path.join(dir, 'STORYBOARD.md');
const sb = fs.readFileSync(sbPath, 'utf8');
const a = sb.indexOf(start), b = sb.indexOf(end);
if (a < 0 || b < 0) { console.error('STORYBOARD.md is missing the capture-table markers'); process.exit(2); }
const newSb = `${sb.slice(0, a + start.length)}\n\n${table()}\n\n${sb.slice(b)}`;
const newScript = script();
const scriptPath = path.join(dir, 'capture.sh');
if (mode === 'write') {
  fs.writeFileSync(sbPath, newSb);
  fs.writeFileSync(scriptPath, newScript, { mode: 0o755 });
  console.log(`wrote capture.sh (${shot.length} captures) and the capture table (${manifest.captures.length} rows)`);
} else {
  const stale = [];
  if (newSb !== sb) stale.push('STORYBOARD.md capture table');
  if (!fs.existsSync(scriptPath) || fs.readFileSync(scriptPath, 'utf8') !== newScript) stale.push('capture.sh');
  if (stale.length) { console.error(`out of date: ${stale.join(', ')} (run: node tools/gen-capture.mjs --write)`); process.exit(1); }
  console.log('capture.sh and the STORYBOARD.md capture table match capture-manifest.json');
}
